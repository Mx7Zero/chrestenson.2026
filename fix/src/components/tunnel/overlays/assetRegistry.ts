export type AssetEntry = {
  id: string
  name: string
  viewBox: string
  d: string
  category: AssetCategory
  tags: string[]
  recommendedModes: OverlayType[]
  source?: string  // attribution, when imported from a third-party pack
  license?: string // e.g. 'MIT'
  // Procedural assets carry a generator. When set, the overlay
  // renderer calls `generate(layer.assetSeed)` to produce fresh path
  // data per layer-seed. The static `d` and `viewBox` above act as
  // a stable fallback for the picker thumbnail.
  procedural?: boolean
  // Effect assets render full-bleed animated SVG (laser fan, plasma,
  // god rays, etc.) instead of a path. The static `d` is only used
  // for the picker thumbnail. The renderer dispatches via effectId
  // to the right EffectSVG component.
  effectId?: EffectId
}

// Resolve an asset against an optional seed. Static assets ignore
// the seed; procedural assets re-derive the path from it.
export function resolveAssetPath(
  asset: AssetEntry,
  seed?: number,
): { d: string; viewBox: string } {
  if (asset.procedural) {
    const gen: ProcGenerator | undefined = PROC_GENERATORS[asset.id]
    if (gen) {
      const out = gen((seed ?? 1) >>> 0)
      return out
    }
  }
  return { d: asset.d, viewBox: asset.viewBox }
}

