// ─── Overlay asset registry ───────────────────────────────────────
// Hand-authored SVG path data for the overlay layer system. Assets
// are simple geometric/symbolic primitives — not derived from any
// third-party icon library — so the file ships under the same MIT
// license as the rest of the codebase.
//
// To add an asset: append to ASSETS with a fresh id, the right
// category, and a 100×100 viewBox. The OverlayStack scales the path
// dynamically; centering inside [10..90, 10..90] leaves room for
// glow/blur softness without clipping.
//
// Future packs (Tabler, Heroicons, Feather, CoolShapes, pattern
// monster, etc.) drop in as additional ASSETS entries, with `source`
// + `license` populated and the upstream attribution preserved.

